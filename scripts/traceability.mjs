// Builds project-docs/05-delivery/traceability.md from PRD requirement IDs and task files.
// Usage: node scripts/traceability.mjs   (exit code 1 if a non-pending, non-deferred requirement has no task)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'project-docs');
const prd = readFileSync(join(root, '02-product/PRD.md'), 'utf8');
const reqs = [...prd.matchAll(/\*\*([A-Z]+-\d+) ([^*]+)\*\*\s*·\s*([a-z-]+)/g)].map(m => ({ id: m[1], title: m[2].trim(), status: m[3] }));
const nfr = [...prd.matchAll(/- (NFR-\d+) ([^:]+):/g)].map(m => ({ id: m[1], title: m[2].trim(), status: 'draft' }));
const all = [...reqs, ...nfr];
const tdir = join(root, '05-delivery/tasks');
const map = Object.fromEntries(all.map(r => [r.id, []]));
for (const f of readdirSync(tdir)) {
  const txt = readFileSync(join(tdir, f), 'utf8');
  for (const block of txt.split(/^### /m).slice(1)) {
    const tid = block.match(/^(T-\d+)/)?.[1]; if (!tid) continue;
    const reqLine = block.match(/Req:([^\n·]+(?:·[^\n]*)?)/)?.[1] ?? '';
    const ids = new Set();
    for (const m of reqLine.matchAll(/([A-Z]+)-(\d+)(?:\.\.(\d+))?/g)) {
      if (m[3]) for (let i = +m[2]; i <= +m[3]; i++) ids.add(`${m[1]}-${String(i).padStart(2, '0')}`);
      else ids.add(`${m[1]}-${m[2]}`);
    }
    for (const id of ids) if (map[id]) map[id].push(`${tid} (${f.replace('.md', '')})`);
  }
}
let out = '# Traceability — Requirement → Task\n\nGenerated by `scripts/traceability.mjs`. Do not edit by hand.\n\n| Requirement | Title | Status | Tasks | Flag |\n|---|---|---|---|---|\n';
let missing = 0;
for (const r of all) {
  const t = map[r.id];
  let flag = '';
  if (!t.length) { flag = r.status === 'pending-client' ? '⏸ pending client' : r.status === 'deferred' ? '⏭ deferred (post-MVP)' : '⚠ NO TASK'; if (r.status !== 'pending-client' && r.status !== 'deferred') missing++; }
  out += `| ${r.id} | ${r.title} | ${r.status} | ${t.join(', ') || '—'} | ${flag} |\n`;
}
out += `\nTotal requirements: ${all.length} · without task (excluding pending-client and deferred): ${missing}\n`;
writeFileSync(join(root, '05-delivery/traceability.md'), out);
console.log(`requirements=${all.length} missing=${missing}`);
process.exit(missing ? 1 : 0);
